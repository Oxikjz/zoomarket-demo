# фото из assets/img/p/NN.webp: пул по животному, для части разделов свой
POOLS = {'cats': [34, 35, 36, 37, 39, 40], 'dogs': [29, 30, 31, 32, 33], 'rodents': [0, 25, 26, 27],
         'birds': [8, 11], 'fish': [4], 'reptiles': [24, 28, 19, 20], 'farm': [9]}
SUB_POOLS = {('cats', 'Сухие корма'): [37, 39], ('cats', 'Влажные корма'): [36, 37, 39], ('cats', 'Игрушки'): [34, 35, 40]}

def photo(animal, sub):
    return 'assets/img/p/%02d.webp' % random.choice(SUB_POOLS.get((animal, sub), POOLS[animal]))

def price(lo, hi):
    v = random.randint(lo, hi)
    return max(lo, round(v / 10) * 10 - random.choice([1, 0, 0, 1]))

products, n = [], 0
for animal, subs in CATALOG.items():
    for sub, (names, sizes, (lo, hi)) in subs.items():
        pool = [(t, s) for t in names for s in sizes]
        random.shuffle(pool)
        for t, s in pool[: random.randint(8, 16)]:
            b = random.choice(BRANDS)
            n += 1
            st = {k: 1 for k in STORES if random.random() < 0.55}
            if n % 11 == 0: st = {}
            products.append({'id': f'd{n:04d}', 'name': (t.format(b=b) + (', ' + s if s else '')).strip(), 'animals': [animal],
                             'sub': sub, 'g3': b, 'grp': sub, 'price': price(lo, hi), 'stock': st, 'img': photo(animal, sub)})
random.shuffle(products)
out = pathlib.Path(__file__).resolve().parent.parent / 'data'
out.mkdir(exist_ok=True)
now = datetime.datetime(2026, 1, 1, 12, 0).isoformat(timespec='minutes')
(out / 'catalog.json').write_text(json.dumps({'updated': now, 'demo': True, 'products': products}, ensure_ascii=False, separators=(',', ':')))
mask = {p['id']: sum(1 << i for i, k in enumerate(STORES) if p['stock'].get(k)) for p in products if p['stock']}
(out / 'stock.json').write_text(json.dumps({'updated': now, 'stores': STORES, 's': mask}, separators=(',', ':')))
(out / 'bonus.json').write_text(json.dumps({'active': True, 'name': 'Бонусная карта', 'earnRub': 10, 'pointRub': 1, 'maxPct': 5, 'delayDays': 3, 'welcome': 100, 'updated': now}, ensure_ascii=False))
print(len(products), 'товаров')
